import {spawn} from 'node:child_process';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {randomBytes} from 'node:crypto';
import net from 'node:net';
import https from 'node:https';
import path from 'node:path';
import os from 'node:os';
import {fileURLToPath} from 'node:url';
if(process.env.BCI_PROVIDER_LAB!=='1' || !process.env.BCI_VAULT_BIN)throw new Error('explicit isolated Vault lab and real executable required');
const directory=await mkdtemp(path.join(os.tmpdir(),'bci-vault-lab-')),token=randomBytes(32).toString('hex'),root=fileURLToPath(new URL('../',import.meta.url));
const reservation=net.createServer();await new Promise((r)=>reservation.listen(0,'127.0.0.1',r));const port=reservation.address().port;await new Promise((r)=>reservation.close(r));
const vault=spawn(process.env.BCI_VAULT_BIN,['server','-dev','-dev-tls',`-dev-listen-address=127.0.0.1:${port}`,`-dev-tls-cert-dir=${directory}`],{env:{...process.env,VAULT_DEV_ROOT_TOKEN_ID:token},stdio:'ignore',windowsHide:true});
const stopped=new Promise((resolve)=>{vault.once('exit',resolve);vault.once('error',resolve);});
try{
 let ready=false;for(let i=0;i<100;i++){
  if(vault.exitCode!==null)throw new Error('isolated Vault exited');
  try{const ca=await readFile(path.join(directory,'vault-ca.pem'));ready=await new Promise((resolve)=>{const req=https.get(`https://127.0.0.1:${port}/v1/sys/health`,{ca,timeout:1000},(res)=>{res.resume();resolve(res.statusCode===200);});req.on('error',()=>resolve(false));req.on('timeout',()=>req.destroy());});if(ready)break;}catch{/* CA is generated by the real server at startup. */}
  await new Promise((r)=>setTimeout(r,300));
 }
 if(!ready)throw new Error('isolated TLS Vault did not become healthy');
 const env={...process.env,BCI_PENTEST_VAULT_URL:`https://127.0.0.1:${port}`,BCI_PENTEST_VAULT_TOKEN:token,BCI_PENTEST_VAULT_OPERATOR_TOKEN:token,NODE_EXTRA_CA_CERTS:path.join(directory,'vault-ca.pem')};
 const test=spawn(process.execPath,['node_modules/vitest/vitest.mjs','run','--config','vitest.providers.config.js','--reporter=default','--reporter=json','--outputFile=evidence/production-completion/provider-results.json'],{cwd:root,env,stdio:'inherit',windowsHide:true});
 process.exitCode=await new Promise((resolve)=>{test.on('error',()=>resolve(1));test.on('exit',(code)=>resolve(code ?? 1));});
}finally{
 vault.kill();await stopped;
 if(!path.resolve(directory).startsWith(path.join(path.resolve(os.tmpdir()),'bci-vault-lab-')))throw new Error('unexpected lab cleanup path');
 await rm(directory,{recursive:true,force:true});
}
